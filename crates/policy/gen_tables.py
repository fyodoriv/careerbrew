"""Generate crates/policy/src/tables.rs from the pinned CPython's Unicode data.

Usage: python -I crates/policy/gen_tables.py crates/policy/src/tables.rs

The policy crate must answer like Python's `str` methods and `re`, not like
Rust's own Unicode tables (docs/rust-migration.md, rust-04 "Traps to
remember"). Every table here comes from the interpreter that runs the oracle,
so a Python upgrade that moves its Unicode version shows up as a new table
and a new `UNIDATA_VERSION`.
"""

from __future__ import annotations

import _sre
import re._casefix as casefix
import sys
import unicodedata
from collections.abc import Callable
from pathlib import Path


def _ranges(pred: Callable[[str], bool]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or not pred(chr(cp)):
            continue
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def _table(name: str, doc: str, ranges: list[tuple[int, int]]) -> str:
    rows = "\n".join(f"    (0x{lo:x}, 0x{hi:x})," for lo, hi in ranges)
    return f"/// {doc}\npub const {name}: &[(u32, u32)] = &[\n{rows}\n];\n"


def _esc(text: str) -> str:
    return "".join(f"\\u{{{ord(c):x}}}" for c in text)


def render() -> str:
    parts = [
        "//! Generated by `python -I crates/policy/gen_tables.py`; do not edit.\n",
        f"/// `unicodedata.unidata_version` of the generating Python ({sys.version.split()[0]}).",
        f'pub const UNIDATA_VERSION: &str = "{unicodedata.unidata_version}";\n',
        _table("ALNUM", "`str.isalnum` per char.", _ranges(str.isalnum)),
        _table("ALPHA", "`str.isalpha` per char.", _ranges(str.isalpha)),
        _table("DIGIT", "`str.isdigit` per char.", _ranges(str.isdigit)),
        _table("DECIMAL", "`re` `\\d` in a str pattern (`str.isdecimal`).", _ranges(str.isdecimal)),
        _table("SPACE", "`str.isspace` per char (also `re` `\\s`).", _ranges(str.isspace)),
        _table(
            "ASSIGNED",
            "Chars assigned in this Unicode version (general category not `Cn`); NFKC leaves the others as they are.",
            _ranges(lambda c: unicodedata.category(c) != "Cn"),
        ),
    ]
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        simple = _sre.unicode_tolower(cp)
        full = chr(cp).lower()
        if simple != cp or full != chr(cp):
            rows.append(f'    (0x{cp:x}, 0x{simple:x}, "{_esc(full)}"),')
    parts.append("/// (char, `re` simple lowercase, `str.lower` of the char alone) for every char\n/// that one of them changes, in code point order.\npub const LOWER: &[(u32, u32, &str)] = &[\n" + "\n".join(rows) + "\n];\n")
    groups = sorted({tuple(sorted((k, *v))) for k, v in casefix._EXTRA_CASES.items()})
    grows = "\n".join("    &[" + ", ".join(f"0x{c:x}" for c in g) + "]," for g in groups)
    parts.append("/// `re._casefix._EXTRA_CASES` as groups: chars `re.IGNORECASE` treats as equal\n/// beyond their simple lowercase.\npub const EXTRA_CASES: &[&[u32]] = &[\n" + grows + "\n];\n")
    return "\n".join(parts)


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print("usage: gen_tables.py <out.rs>", file=sys.stderr)
        return 2
    Path(argv[0]).write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
