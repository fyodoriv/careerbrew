#!/usr/bin/env python3
"""Write the generated action registry and the native route table (rust-03).

    uv run python scripts/gen-registry.py          write both files
    uv run python scripts/gen-registry.py --check  exit 1 when either file is stale (the `registry` gate step)

The CLI parser stays the source until rust-26. This script walks it once and writes
crates/cbcli/registry/registry.json:
  meta   the Python minor version, the help width, and the row count
  notes  TERMINAL_ONLY, CONFIRM, YES_FROM_CONFIRM, and AGENT_NOTES, verbatim
  rows   the exact `careerbrew actions --json` rows
  help   each parser path ("" for the root, "day", "config set") to its --help text at 80 columns
`actions.catalog()`, the web app's Actions view, and the native pilot binary read this file.

It also writes config/native-routes.txt: one `<action> <python|native>` line per action. A new
action starts as `python`; an existing line keeps its route.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "crates" / "cbcli" / "registry" / "registry.json"
ROUTES = ROOT / "config" / "native-routes.txt"
COLUMNS = 80
ROUTE_VALUES = ("python", "native")
ROUTES_HEADER = "# Per-action route for the console script (rust-03): `<action> <python|native>`.\n# Generated by scripts/gen-registry.py; a new action starts as python. Change one line to switch it.\n"


def _help_texts(parser: argparse.ArgumentParser, path: tuple[str, ...] = ()) -> dict[str, str]:
    out = {" ".join(path): parser.format_help()}
    for a in parser._actions:
        if isinstance(a, argparse._SubParsersAction):
            for name, sp in a.choices.items():
                out.update(_help_texts(sp, (*path, name)))
    return out


def export() -> dict[str, Any]:
    """The registry, built in memory at a pinned help width."""
    from careerbrew import actions
    from careerbrew.cli import build_parser

    saved = {k: os.environ.get(k) for k in ("COLUMNS", "LINES")}
    os.environ["COLUMNS"], os.environ["LINES"] = str(COLUMNS), "24"  # argparse reads the width from COLUMNS
    try:
        rows = json.loads(json.dumps(actions.catalog_from_parser()))
        help_texts = _help_texts(build_parser())
    finally:
        for k, v in saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v
    return {
        "meta": {"python": f"{sys.version_info.major}.{sys.version_info.minor}", "columns": COLUMNS, "rows": len(rows)},
        "notes": {
            "terminal_only": actions.TERMINAL_ONLY,
            "confirm": actions.CONFIRM,
            "yes_from_confirm": sorted(actions.YES_FROM_CONFIRM),
            "agent_notes": actions.AGENT_NOTES,
        },
        "rows": rows,
        "help": help_texts,
    }


def render(registry: dict[str, Any]) -> str:
    return json.dumps(registry, indent=1) + "\n"


def read_routes(text: str) -> dict[str, str]:
    routes: dict[str, str] = {}
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) == 2 and parts[1] in ROUTE_VALUES:
            routes[parts[0]] = parts[1]
    return routes


def render_routes(names: list[str], old: dict[str, str]) -> str:
    return ROUTES_HEADER + "".join(f"{n} {old.get(n, 'python')}\n" for n in names)


def stale(registry_text: str, routes_text: str) -> list[str]:
    """What differs between the committed files and a fresh export: paths, never content."""
    fresh = export()
    found: list[str] = []
    try:
        old = json.loads(registry_text)
    except ValueError:
        return [str(REGISTRY.relative_to(ROOT))]
    for key in fresh:
        if key in ("rows", "help"):
            continue
        if old.get(key) != fresh[key]:
            found.append(key)
    old_rows = {r.get("name"): r for r in old.get("rows", [])}
    new_rows = {r["name"]: r for r in fresh["rows"]}
    found += [f"rows.{n}" for n in sorted(set(old_rows) | set(new_rows)) if old_rows.get(n) != new_rows.get(n)]
    if [r.get("name") for r in old.get("rows", [])] != list(new_rows) and not any(f.startswith("rows.") for f in found):
        found.append("rows (order)")
    old_help, new_help = old.get("help", {}), fresh["help"]
    found += [f"help[{p!r}]" for p in sorted(set(old_help) | set(new_help)) if old_help.get(p) != new_help.get(p)]
    if not found and registry_text != render(fresh):
        found.append(str(REGISTRY.relative_to(ROOT)) + " (formatting)")
    names = [r["name"] for r in fresh["rows"]]
    if routes_text != render_routes(names, read_routes(routes_text)):
        found.append(str(ROUTES.relative_to(ROOT)))
    return found


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    p.add_argument("--check", action="store_true", help="exit 1 when the committed files are stale; write nothing")
    a = p.parse_args(argv)
    registry_text = REGISTRY.read_text(encoding="utf-8") if REGISTRY.exists() else ""
    routes_text = ROUTES.read_text(encoding="utf-8") if ROUTES.exists() else ""
    if a.check:
        found = stale(registry_text, routes_text)
        if found:
            print("gen-registry: the action registry is stale: " + ", ".join(found[:20]) + (f" (+{len(found) - 20} more)" if len(found) > 20 else ""), file=sys.stderr)
            print("fix: uv run python scripts/gen-registry.py", file=sys.stderr)
            return 1
        print("gen-registry: registry and routes match the CLI parser")
        return 0
    for line in routes_text.splitlines():
        if line.strip() and not line.startswith("#") and (len(line.split()) != 2 or line.split()[1] not in ROUTE_VALUES):
            print(f"gen-registry: bad route line {line!r}; expected `<action> <python|native>`", file=sys.stderr)
            return 1
    fresh = export()
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY.write_text(render(fresh), encoding="utf-8")
    ROUTES.write_text(render_routes([r["name"] for r in fresh["rows"]], read_routes(routes_text)), encoding="utf-8")
    print(f"gen-registry: wrote {fresh['meta']['rows']} action(s) and {len(fresh['help'])} help page(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
